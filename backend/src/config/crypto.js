import crypto from 'node:crypto';
import { env } from './env.js';

const ALGORITHM = 'aes-256-gcm';
const IV_LENGTH = 12; // Recommended 96-bit IV for GCM
const KEY_BUFFER = Buffer.from(env.encryptionKey, 'hex');

/**
 * Encrypt sensitive text (e.g., OpenAI/Gemini API keys) with AES-256-GCM.
 * Format: ivHex:authTagHex:ciphertextHex
 */
export function encryptSecret(plaintext) {
  if (plaintext === null || plaintext === undefined || plaintext === '') {
    return '';
  }

  const iv = crypto.randomBytes(IV_LENGTH);
  const cipher = crypto.createCipheriv(ALGORITHM, KEY_BUFFER, iv);
  const encrypted = Buffer.concat([cipher.update(String(plaintext), 'utf8'), cipher.final()]);
  const authTag = cipher.getAuthTag();

  return `${iv.toString('hex')}:${authTag.toString('hex')}:${encrypted.toString('hex')}`;
}

/**
 * Decrypt AES-256-GCM payload previously generated by encryptSecret().
 */
export function decryptSecret(payload) {
  if (!payload || typeof payload !== 'string') {
    return '';
  }

  const parts = payload.split(':');
  if (parts.length !== 3) {
    throw new Error('Invalid encrypted secret format.');
  }

  const [ivHex, authTagHex, encryptedHex] = parts;
  const iv = Buffer.from(ivHex, 'hex');
  const authTag = Buffer.from(authTagHex, 'hex');
  const encrypted = Buffer.from(encryptedHex, 'hex');

  const decipher = crypto.createDecipheriv(ALGORITHM, KEY_BUFFER, iv);
  decipher.setAuthTag(authTag);

  const decrypted = Buffer.concat([decipher.update(encrypted), decipher.final()]);
  return decrypted.toString('utf8');
}

/**
 * Mask a secret key for safe Admin UI display (never returns full key).
 * Example: "sk-proj-1234567890abcdef" -> "sk-p...cdef"
 */
export function maskSecret(secret) {
  if (!secret || typeof secret !== 'string') {
    return '';
  }

  const trimmed = secret.trim();
  if (trimmed.length === 0) {
    return '';
  }
  if (trimmed.length <= 8) {
    return '****';
  }

  return `${trimmed.slice(0, 4)}...${trimmed.slice(-4)}`;
}
